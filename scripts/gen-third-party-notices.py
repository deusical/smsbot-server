#!/usr/bin/env python3
"""Regenerate THIRD_PARTY_NOTICES.md from the dependencies actually shipped.

Go modules are those compiled into ./cmd/smsbot (`go list -deps`); npm packages are
the production dependencies bundled into the dashboard. Run from the repository
root after `npm ci` in web/:  python scripts/gen-third-party-notices.py
"""
import json
import re
import shutil
import subprocess
from pathlib import Path

root = Path(__file__).resolve().parent.parent
out = root / 'THIRD_PARTY_NOTICES.md'
LICENSE_NAMES = re.compile(r'^(licen[sc]e|copying|unlicense|notice)([-_.].*)?$', re.I)


def identify(text):
    t = ' '.join(text.split()).lower()
    if 'gnu affero general public license' in t:
        return 'AGPL-3.0'
    if 'apache license' in t and 'version 2.0' in t:
        return 'Apache-2.0'
    if 'mozilla public license' in t:
        return 'MPL-2.0'
    if 'permission is hereby granted, free of charge' in t:
        return 'MIT'
    if 'redistribution and use in source and binary forms' in t:
        return 'BSD-3-Clause' if 'neither the name' in t or 'may be used to endorse' in t else 'BSD-2-Clause'
    if 'unlicense' in t or 'this is free and unencumbered software' in t:
        return 'Unlicense'
    return 'see text'


def license_files(directory):
    files = sorted(p for p in Path(directory).iterdir() if p.is_file() and LICENSE_NAMES.match(p.name))
    return [p for p in files if p.stat().st_size < 200_000]


def go_modules():
    raw = subprocess.run(['go', 'list', '-deps', '-f', '{{with .Module}}{{.Path}}\t{{.Version}}\t{{.Dir}}{{end}}', './cmd/smsbot'],
                         cwd=root, check=True, capture_output=True, text=True).stdout
    mods = {}
    for line in raw.splitlines():
        if not line.strip():
            continue
        path, version, directory = line.split('\t')
        if path != 'smsbot-server':
            mods[path] = (version, directory)
    return dict(sorted(mods.items()))


def npm_packages():
    tree = json.loads(subprocess.run([shutil.which('npm'), 'ls', '--omit=dev', '--all', '--json'], cwd=root / 'web',
                                     capture_output=True, text=True).stdout)
    found = {}

    def walk(node):
        for name, info in (node.get('dependencies') or {}).items():
            found[name] = info.get('version')
            walk(info)
    walk(tree)
    return dict(sorted(found.items()))


def section(title, directory, version):
    files = license_files(directory)
    texts = [(f.name, f.read_text(encoding='utf-8', errors='replace').strip()) for f in files]
    kind = identify(texts[0][1]) if texts else 'unknown'
    parts = [f'### {title} {version}', '', f'License: {kind}', '']
    if not texts:
        parts += ['_No license file was found in the module; check its repository._', '']
    for name, text in texts:
        parts += [f'<details><summary>{name}</summary>', '', '```text', text, '```', '', '</details>', '']
    return '\n'.join(parts), kind


lines = ['# Third-party notices', '',
         'SmsBot Server is licensed under the GNU Affero General Public License v3.0 or later (see `LICENSE`).',
         'It builds on the open-source software below. Each component keeps its own license and copyright;',
         'these notices must be preserved when you redistribute the program or its source.', '',
         'The Google Messages adapter uses [mautrix/gmessages libgm](https://github.com/mautrix/gmessages) and `go.mau.fi/util` (both AGPL-3.0).',
         'SmsBot is an independent project and is not affiliated with or endorsed by Google or the mautrix project.', '',
         '_Generated by `scripts/gen-third-party-notices.py` from the dependencies shipped in the binary. Regenerate it when dependencies change._', '',
         '## Go modules compiled into the service', '']
summary = []
for path, (version, directory) in go_modules().items():
    body, kind = section(path, directory, version)
    lines.append(body)
    summary.append((path, version, kind))
lines += ['## npm packages bundled into the dashboard', '']
for name, version in npm_packages().items():
    package = root / 'web' / 'node_modules' / name
    body, kind = section(name, package, version)
    lines.append(body)
    summary.append((name, version, kind))
out.write_text('\n'.join(lines).rstrip() + '\n', encoding='utf-8', newline='\n')
for entry in summary:
    print('%-45s %-45s %s' % entry)
